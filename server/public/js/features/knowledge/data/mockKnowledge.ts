/**
 * Knowledge モジュール型定義
 */

export interface KnowledgeItem {
  id: string;
  title: string;
  summary: string;
  /** 大分類（ジャンルタブで絞り込み） */
  genre: string;
  tags: string[];
  /**
   * 添付メディア URL（互換のため
   * フィールド名は pdf_url のまま）。
   * PDF / 写真 / 動画を格納する。
   */
  pdf_url?: string | null;
  /** 複数添付（新形式） */
  medias?: Array<{
    url: string;
    fileName?: string;
    kind?: "pdf" | "image" | "video" | "unknown";
  }>;
  /** URL 配列・単一値の既存形式も読み取り対象 */
  files?: Array<string | { url: string; fileName?: string }>;
  media?: string | { url: string; fileName?: string } | null;
  file?: string | { url: string; fileName?: string } | null;
  createdAt: string;
  /** 本文詳細（任意・既存カードは未設定のまま） */
  body?: string;
  /** 8統一ジャンル（既存 genre は維持） */
  unifiedGenre?: string;
}

