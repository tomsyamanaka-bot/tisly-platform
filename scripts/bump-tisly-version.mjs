/**
 * ルートの npm run build（prebuild）でだけパッチを +1 する。
 * VPS の server/ 内ビルドはこのスクリプトを呼ばない。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

if (process.env.TISLY_SKIP_VERSION_BUMP === "1" || process.env.CI === "true") {
  console.log("[tisly-version] skip (already committed; CI/VPS must not bump again)");
  process.exit(0);
}

function read(rel) {
  return fs.readFileSync(path.join(root, rel), "utf8");
}

function write(rel, text) {
  fs.writeFileSync(path.join(root, rel), text);
}

function parseSemver(value) {
  const match = String(value || "").match(/(\d+)\.(\d+)\.(\d+)/);
  if (!match) return null;
  return [Number(match[1]), Number(match[2]), Number(match[3])];
}

function bumpPatch(version) {
  const parts = parseSemver(version);
  if (!parts) {
    throw new Error(`version is not semver: ${version}`);
  }
  return `${parts[0]}.${parts[1]}.${parts[2] + 1}`;
}

function replaceOnce(text, pattern, replacement, label) {
  if (!pattern.test(text)) {
    throw new Error(`version pattern missing: ${label}`);
  }
  return text.replace(pattern, replacement);
}

const pkgPath = "package.json";
let pkgText = read(pkgPath);
const pkg = JSON.parse(pkgText);
let current = parseSemver(pkg.version);
if (!current) {
  const fw = read("rp2350/firmware/config_toyoshima.py");
  const seeded = fw.match(/OTA_VERSION\s*=\s*"(\d+\.\d+\.\d+)"/);
  current = parseSemver(seeded?.[1] || "1.2.19");
}
const next = bumpPatch(
  `${current[0]}.${current[1]}.${current[2]}`
);

if (/"version"\s*:/.test(pkgText)) {
  pkgText = replaceOnce(
    pkgText,
    /"version"\s*:\s*"[^"]+"/,
    `"version": "${next}"`,
    "package.json version"
  );
} else {
  pkgText = pkgText.replace(
    /("name"\s*:\s*"[^"]+",\n)/,
    `$1  "version": "${next}",\n`
  );
}
write(pkgPath, pkgText);

write(
  "rp2350/firmware/toyoshima_security.py",
  replaceOnce(
    read("rp2350/firmware/toyoshima_security.py"),
    /FIRMWARE_LOGIC_VERSION = "\d+\.\d+\.\d+"/,
    `FIRMWARE_LOGIC_VERSION = "${next}"`,
    "toyoshima_security.py"
  )
);

let config = read("rp2350/firmware/config_toyoshima.py");
config = replaceOnce(
  config,
  /FIRMWARE_VERSION = "\d+\.\d+\.\d+[^"]*"/,
  `FIRMWARE_VERSION = "${next}"`,
  "config FIRMWARE_VERSION"
);
config = replaceOnce(
  config,
  /OTA_VERSION = "\d+\.\d+\.\d+"/,
  `OTA_VERSION = "${next}"`,
  "config OTA_VERSION"
);
write("rp2350/firmware/config_toyoshima.py", config);

write(
  "server/public/js/tisly-release-version-v1.js",
  `/** Generated by scripts/bump-tisly-version.mjs. Do not edit by hand. */
export const TISLY_RELEASE_VERSION = "${next}";

export function tislySystemVersionLabel(deviceVersion) {
  const release = \`v\${TISLY_RELEASE_VERSION}\`;
  const raw = String(deviceVersion ?? "")
    .trim()
    .replace(/^v/i, "")
    .split("-")[0];
  if (!raw || raw === "―" || raw === TISLY_RELEASE_VERSION) return release;
  return \`\${release}（実機 v\${raw}）\`;
}
`
);

console.log(`[tisly-version] ${current.join(".")} -> ${next}`);
