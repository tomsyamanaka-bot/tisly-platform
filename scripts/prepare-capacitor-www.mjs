#!/usr/bin/env node
/**
 * Copy server/public → www for Capacitor webDir.
 * Does not modify source PWA assets.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const src = path.join(root, "server", "public");
const dest = path.join(root, "www");

function fail(msg) {
  console.error(`[prepare-capacitor-www] ERROR: ${msg}`);
  process.exit(1);
}

function copyRecursive(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, entry.name);
    const d = path.join(to, entry.name);
    if (entry.isDirectory()) {
      copyRecursive(s, d);
    } else if (entry.isFile()) {
      fs.copyFileSync(s, d);
    }
  }
}

if (!fs.existsSync(src)) fail(`Missing source: ${src}`);

if (fs.existsSync(dest)) {
  fs.rmSync(dest, { recursive: true, force: true });
}
copyRecursive(src, dest);

// Keep VCS placeholders (prepare wipes www/)
fs.writeFileSync(path.join(dest, ".gitkeep"), "", "utf8");
fs.writeFileSync(
  path.join(dest, ".gitignore"),
  "# Capacitor www is generated by `npm run cap:prepare` from server/public\n*\n!.gitkeep\n!.gitignore\n",
  "utf8"
);

const marker = path.join(dest, ".capacitor-www-ready");
fs.writeFileSync(
  marker,
  `preparedAt=${new Date().toISOString()}\nsource=server/public\n`,
  "utf8"
);

console.log(`[prepare-capacitor-www] OK → ${dest}`);
